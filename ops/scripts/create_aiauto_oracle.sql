
-- Run as SYS AS SYSDBA
-- Create common user AIAUTO (C## prefix required for CDB)
CREATE USER C##AIAUTO IDENTIFIED BY root;
GRANT DBA TO C##AIAUTO;
GRANT CREATE SESSION TO C##AIAUTO CONTAINER=ALL;
GRANT CONNECT, RESOURCE TO C##AIAUTO CONTAINER=ALL;

-- Also create in each PDB without C## prefix
ALTER SESSION SET CONTAINER = PDB1;
CREATE USER AIAUTO IDENTIFIED BY root;
GRANT DBA TO AIAUTO;
GRANT CONNECT, RESOURCE TO AIAUTO;

ALTER SESSION SET CONTAINER = SOLE;
CREATE USER AIAUTO IDENTIFIED BY root;
GRANT DBA TO AIAUTO;
GRANT CONNECT, RESOURCE TO AIAUTO;

ALTER SESSION SET CONTAINER = LUNA;
CREATE USER AIAUTO IDENTIFIED BY root;
GRANT DBA TO AIAUTO;
GRANT CONNECT, RESOURCE TO AIAUTO;

-- Back to CDB
ALTER SESSION SET CONTAINER = CDB$ROOT;
COMMIT;
